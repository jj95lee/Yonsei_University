% 두 일차함수 정의
% 첫 번째 일차함수: y = -x + 1344
% 두 번째 일차함수: y = (71/30)x + 1008

% x 값 범위 설정
x = 0:0.1:360;

% 일차함수 계산
y1 = -x + 1344;
y2 = (71/30)*x + 1008;

% 그래프 그리기
figure; % 새로운 그림 창 열기
plot(x, y1, 'r', 'LineWidth', 2); % 첫 번째 일차함수, 빨간색, 선 두께 2
hold on; % 현재 그래프에 추가

plot(x, y2, 'b', 'LineWidth', 2); % 두 번째 일차함수, 파란색, 선 두께 2

% 그래프 제목과 축 라벨 추가
title('두 일차함수 그래프');
xlabel('x 값');
ylabel('y 값');

% 범례 추가
legend('y = -x + 1344', 'y = (71/30)x + 1008');

% 격자 추가
grid on;

% 축 범위 설정
xlim([0 360]);
ylim([1000 1800]);
